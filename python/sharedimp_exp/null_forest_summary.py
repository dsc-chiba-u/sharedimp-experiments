"""Summary of the null-design forest study (workflow 04c).

    python -m sharedimp_exp.null_forest_summary config/04c_null_forest.json results/raw/04c_null_forest results/summary/04c_null_forest

The unit of replication is the simulated data set: the importance of a data
set is the mean over its anchors and splits of MSE(Reduced) - MSE(Full).
"Standard error" is the Monte Carlo standard error of the mean over the data
sets (SD / sqrt(number of data sets)); it describes the simulation, not an
importance. Nothing is checked here: every number is reported.
"""

from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pandas as pd

from .common import ROOT, read_json, write_csv
from .rf_settings_summary import md_table


def main(argv: list[str]) -> int:
    cfg, raw, out = read_json(Path(argv[1])), Path(argv[2]), Path(argv[3])
    rows, paired, runs, per_ds = [], [], [], {}
    for design, d in cfg["designs"].items():
        for variant, v in cfg["variants"].items():
            if not (d["variants"] == "all" or variant in d["variants"]):
                continue
            for lang in v.get("languages", ["r", "python"]):
                df = pd.read_csv(raw / lang / f"{design}__{variant}.csv")
                meta = read_json(raw / lang / f"{design}__{variant}.meta.json")
                df["importance"] = df["mse_reduced"] - df["mse_full"]
                ds = df.groupby("dataset")["importance"].mean()
                per_ds[(lang, design, variant)] = ds
                by_anchor = df.groupby(["dataset", "anchor"])["importance"].mean()
                k = len(ds)
                rows.append({
                    "language": lang, "design": design, "variant": variant, "factor": v["factor"], "datasets": k,
                    "columns_full": int(df["columns_full"].iloc[0]), "columns_reduced": int(df["columns_reduced"].iloc[0]),
                    "candidates_full": int(df["candidates_full"].iloc[0]), "candidates_reduced": int(df["candidates_reduced"].iloc[0]),
                    "mean_importance": ds.mean(), "mc_standard_error": ds.std(ddof=1) / np.sqrt(k), "sd_between_datasets": ds.std(ddof=1),
                    "datasets_with_positive_mean": int((ds > 0).sum()),
                    "share_negative_anchor_values": float((by_anchor < 0).mean()),
                    "excess_mse_full": float((df["mse_full"] - df["mse_null_model"]).mean()),
                    "excess_mse_reduced": float((df["mse_reduced"] - df["mse_null_model"]).mean()),
                    "sd_of_single_split_importance": float(df["importance"].std(ddof=1)),
                })
                runs.append({"language": lang, "design": design, "variant": variant, "seconds": meta["seconds"], "status": meta["status"],
                             "in_pinned_image": meta["in_pinned_image"], "experiments_commit": meta["experiments_commit"],
                             "experiments_code_dirty": meta["experiments_code_dirty"], "settings": str(meta["settings"])})
    for (lang, design, variant), ds in per_ds.items():
        if variant == "baseline":
            continue
        diff = ds - per_ds[(lang, design, "baseline")]
        paired.append({"language": lang, "design": design, "variant": variant, "mean_change_from_baseline": diff.mean(),
                       "mc_standard_error": diff.std(ddof=1) / np.sqrt(len(diff))})
    summary, paired, runs = pd.DataFrame(rows), pd.DataFrame(paired), pd.DataFrame(runs)
    write_csv(summary, out / "summary.csv")
    write_csv(paired, out / "paired_with_baseline.csv")
    write_csv(runs, out / "runs.csv")

    fmt = {c: ".4f" for c in ("mean_importance", "mc_standard_error", "sd_between_datasets", "excess_mse_full", "excess_mse_reduced",
                              "sd_of_single_split_importance", "mean_change_from_baseline")}
    fmt["share_negative_anchor_values"] = ".2f"
    text = ["<!-- generated by python/sharedimp_exp/null_forest_summary.py; do not edit -->", "",
            "## Null design: importance of a forest when the response is independent of the features", "",
            f"Model: {cfg['model']}. Metric: {cfg['metric']}. {cfg['datasets_per_design']} data sets per design, {cfg['folds']} folds, "
            "the same data, folds and seeds in every variant. `mean_importance` is the mean over data sets of the data-set mean (over anchors and splits); "
            "`mc_standard_error` is its Monte Carlo standard error (SD between data sets / sqrt(number of data sets)). "
            "`excess_mse_*` is the MSE of the model minus the MSE of predicting the training mean (positive: worse than no model).", ""]
    for design, d in cfg["designs"].items():
        text += [f"### {design} (n = {d['n']}, p = {d['p']}): {d['note']}", ""]
        for lang in ("r", "python"):
            s = summary[(summary["design"] == design) & (summary["language"] == lang)]
            text += [f"{'R (ranger)' if lang == 'r' else 'Python (scikit-learn)'}:", "",
                     md_table(s[["variant", "factor", "columns_full", "columns_reduced", "candidates_full", "candidates_reduced", "mean_importance",
                                 "mc_standard_error", "datasets_with_positive_mean", "share_negative_anchor_values", "excess_mse_full", "excess_mse_reduced"]], fmt), ""]
    text += ["## Change from the baseline (same data sets, paired)", "",
             md_table(paired.pivot_table(index=["design", "variant"], columns="language", values=["mean_change_from_baseline", "mc_standard_error"], sort=False)
                      .pipe(lambda t: t.set_axis([f"{a}_{b}" for a, b in t.columns], axis=1)).reset_index(), {}), "",
             "## Variants", "",
             md_table(pd.DataFrame([{"variant": k, "factor": v["factor"], "change": str(v["change"]) if v["change"] else "-", "note": v.get("note", "")}
                                    for k, v in cfg["variants"].items()])), "",
             f"Baseline: {cfg['baseline']['note']}; settings {({k: v for k, v in cfg['baseline'].items() if k != 'note'})}.", ""]
    (ROOT / "results" / "tables" / "04c_null_forest.md").write_text("\n".join(text))
    print(f"[null_forest_summary] {len(summary)} cells")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
