"""Data of the runtime benchmark (experiment D).

    python -m sharedimp_exp.runtime_data config/05_runtime.json

Writes data/runtime/rt_n<n>_p<p>.csv for every (n, p) of the candidate and
pilot cells (columns: one fold_v<v> per value of the v sweep, y, x1..xp;
6 decimals) and data/runtime/manifest.json (sha256 per file). The CSV files
are not tracked by git (several MB); the manifest is, so a regenerated file
is verified against it by both languages.
"""

from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pandas as pd

from .common import DATA, read_json, sha256, write_json
from .make_synthetic import balanced_folds

OUT = DATA / "runtime"


def candidate_cells(cfg: dict) -> list[dict]:
    """Candidate cells of the main benchmark, each with the sweeps it belongs to."""
    base = cfg["base"]
    cells: dict[tuple, dict] = {}
    for factor, values in cfg["sweeps"].items():
        for value in values:
            cell = {**base, factor: value}
            key = (cell["n"], cell["p"], cell["v"])
            cells.setdefault(key, {**cell, "sweeps": []})["sweeps"].append(factor)
    return [cells[k] for k in sorted(cells)]


def cell_id(cell: dict) -> str:
    return f"n{cell['n']}_p{cell['p']}_v{cell['v']}"


def data_id(cell: dict) -> str:
    return f"rt_n{cell['n']}_p{cell['p']}"


def main(argv: list[str]) -> int:
    cfg = read_json(Path(argv[1]))
    OUT.mkdir(parents=True, exist_ok=True)
    shapes = sorted({(c["n"], c["p"]) for c in candidate_cells(cfg) + cfg["pilot"]["cells"] + [cfg["pilot"]["fit_count_cell"]]})
    folds = sorted(set(cfg["sweeps"]["v"]) | {c["v"] for c in cfg["pilot"]["cells"]} | {cfg["pilot"]["fit_count_cell"]["v"]})
    files = {}
    for n, p in shapes:
        rng = np.random.default_rng([cfg["data"]["seed"], n, p])
        X = np.empty((n, p))
        X[:, 0] = rng.normal(size=n)
        for j in range(1, p):
            X[:, j] = 0.5 * X[:, j - 1] + np.sqrt(0.75) * rng.normal(size=n)
        y = 2 * X[:, 0] + X[:, 1] - X[:, 2] + 0.5 * X[:, 3] * X[:, 4] + rng.normal(size=n)
        df = pd.DataFrame({f"fold_v{v}": balanced_folds(rng, n, v) for v in folds})
        df["y"] = y
        df = pd.concat([df, pd.DataFrame(X, columns=[f"x{j}" for j in range(1, p + 1)])], axis=1)
        name = f"rt_n{n}_p{p}"
        path = OUT / f"{name}.csv"
        df.to_csv(path, index=False, float_format="%.6f", lineterminator="\n")
        files[name] = {"file": path.name, "sha256": sha256(path), "n": n, "p": p, "fold_columns": [f"fold_v{v}" for v in folds],
                       "features": [f"x{j}" for j in range(1, p + 1)], "target": "y", "bytes": path.stat().st_size}
    write_json({"description": "Synthetic regression data of the runtime benchmark (workflow 05), generated by python/sharedimp_exp/runtime_data.py; "
                               "the CSV files are regenerated by the workflow and are not tracked by git.",
                "generator": cfg["data"], "files": files}, OUT / "manifest.json")
    print(f"[runtime_data] {len(files)} files, {sum(f['bytes'] for f in files.values()) / 1e6:.1f} MB")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
